/**
 * Generates supabase/seed.sql from src/content/defaults.ts.
 * Run: npm run db:seed:generate
 *
 * The seed is idempotent: singleton content and categories/services are
 * inserted only if missing; demo projects are inserted only if their ids
 * are not present (so removing them in the CMS is permanent unless you re-run
 * the seed on purpose).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  defaultCategories,
  defaultContact,
  defaultGeneral,
  defaultHomepage,
  defaultProjects,
  defaultSeo,
  defaultServices,
  defaultStudio,
} from "../src/content/defaults";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table: string, rows: Record<string, unknown>[], conflict = "do nothing", target = "(id)") {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => q(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")})\nvalues\n${values}\non conflict ${target} ${conflict};\n`;
}

const out: string[] = [
  "-- =====================================================================",
  "-- Seed data — GENERATED by scripts/generate-seed.ts from src/content/defaults.ts",
  "-- Do not edit by hand; edit the defaults and run `npm run db:seed:generate`.",
  "-- =====================================================================",
  "",
  "begin;",
  "",
  "-- Singleton content",
  insert("general_settings", [{ id: 1, ...defaultGeneral }]),
  insert("homepage_content", [{ id: 1, ...defaultHomepage }]),
  insert("studio_info", [{ id: 1, ...defaultStudio }]),
  insert("contact_settings", [{ id: 1, ...defaultContact }]),
  insert("seo_settings", defaultSeo as unknown as Record<string, unknown>[], "do nothing", "(page_key)"),
  "-- Categories & services",
  insert("project_categories", defaultCategories as unknown as Record<string, unknown>[]),
  insert("services", defaultServices as unknown as Record<string, unknown>[]),
  "-- Demonstration projects (clearly flagged with is_demo = true)",
];

for (const p of defaultProjects) {
  const { category: _c, translations, images, videos: _v, models: _m, cover_image_id, ...row } = p;
  void _c;
  void _v;
  void _m;
  out.push(`-- ${p.slug}`);
  out.push(insert("projects", [{ ...row, cover_image_id: null }]));
  out.push(insert("project_translations", translations.map((t) => ({ project_id: p.id, ...t })), "do nothing", "(project_id, locale)"));
  out.push(insert("project_images", images as unknown as Record<string, unknown>[]));
  out.push(`update public.projects set cover_image_id = ${q(cover_image_id)} where id = ${q(p.id)} and cover_image_id is null;\n`);
}

out.push("commit;", "");
const file = join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);
